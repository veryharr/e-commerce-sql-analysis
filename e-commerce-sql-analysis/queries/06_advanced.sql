-- TASK 07

-- Find the top 3 products by Revenue for each month.

with month_revenue as (
select DATE_TRUNC('month', o.order_date::date) as month
	, oi.product_id 
	, SUM(oi.price * oi.quantity ) as revenue
from orders o 
join order_items oi on o.order_id = oi.order_id 
group by 1,2
)
, ranked_products AS (
    select *
    	, RANK() OVER (
            PARTITION BY month
            ORDER BY revenue DESC
        ) AS product_rank
    FROM month_revenue
)

select * from ranked_products 
where product_rank <4;





-- TASK 08

-- Calculate cumulative Revenue over time.
-- Example:
-- January   → 10,000
-- February  → 22,000
-- March     → 35,000
-- ...


with month_revenue as (
select DATE_TRUNC('month', o.order_date::date) as month
	
	, SUM(oi.price * oi.quantity ) as revenue
from orders o 
join order_items oi on o.order_id = oi.order_id 
group by 1
)

SELECT
    month,
    revenue AS monthly_revenue,
    SUM(revenue) OVER (ORDER BY month) AS cumulative_revenue
FROM month_revenue
ORDER BY month;
;



-- TASK 09

-- Calculate each product's Revenue
-- as a percentage of the total Revenue of its category.



with prod_revenue as (
select oi.product_id 
	, p.category 
	, SUM(oi.price * oi.quantity ) as revenue
from orders o 
join order_items oi on o.order_id = oi.order_id 
join products p on oi.product_id =p.product_id 
group by 1, 2
),
category_revenue as (
select  p.category 
	, SUM(oi.price * oi.quantity ) as revenue1
from orders o 
join order_items oi on o.order_id = oi.order_id 
join products p on oi.product_id =p.product_id 
group by 1
)

select *
	, ROUND((revenue::numeric/cr.revenue1)*100, 2) as final_amount
from prod_revenue 
JOIN category_revenue cr
    ON prod_revenue.category = cr.category
;

-- TASK 10

-- Find the month in which Revenue increased the most
-- compared to the previous month.
-- Use LAG().


with month_revenue as (
select DATE_TRUNC('month', o.order_date::date) as month
	
	, SUM(oi.price * oi.quantity ) as revenue
from orders o 
join order_items oi on o.order_id = oi.order_id 
group by 1
)

select * 
		, LAG(revenue) OVER (ORDER BY month) AS previous_revenue
		, revenue - LAG(revenue) OVER (ORDER BY month)as raznica
from month_revenue 
;






with sorted_data as (
select o.customer_id 
		, SUM(oi.price * oi.quantity ) as revenue 
		, NTILE(3) OVER (ORDER BY SUM(oi.price * oi.quantity ) DESC) as categorie
		, case 
				when NTILE(3) OVER (ORDER BY SUM(oi.price * oi.quantity ) DESC) = 1 then 'HIGH LEVEL'
				when NTILE(3) OVER (ORDER BY SUM(oi.price * oi.quantity ) DESC) = 2 then 'MID LEVEL'
				when NTILE(3) OVER (ORDER BY SUM(oi.price * oi.quantity ) DESC) = 3 then 'LOW LEVEL'
				END AS customer_segment
from orders o 

join order_items oi on o.order_id = oi.order_id
group by 1 
order by 2 desc
)

select customer_segment
	, COUNT(1) as cos_count
	, SUM(revenue) as segment_revenue
	, round(100.0 * SUM(revenue)/ SUM(SUM(revenue)) OVER (), 2) AS revenue_share_percentage
from sorted_data
group by 1
order by 3 desc
;