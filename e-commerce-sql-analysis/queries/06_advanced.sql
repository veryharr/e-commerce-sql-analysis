-- TASK 01

-- Categorize orders by their total value using CASE WHEN.
-- Low    → less than 100
-- Medium → 100–500
-- High   → more than 500.

select o.order_id 
	, SUM(oi.price * oi.quantity ) as revenue
	,CASE
    WHEN SUM(oi.price * oi.quantity) < 100 THEN 'LOW'
    WHEN SUM(oi.price * oi.quantity) <= 500 THEN 'MEDIUM'
    ELSE 'HIGH'
end as category
from  order_items oi 
join orders o on o.order_id = oi.order_id
group by 1
;


-- TASK 02

-- Use COALESCE to replace NULL values with a default value.
SELECT
    oi.order_id,
    oi.price,
    COALESCE(oi.price, 0) AS price_fixed
FROM order_items oi;
   ;

-- TASK 03

-- Use a CTE (WITH) to perform a more complex analysis.
-- 1)Calculate the total Revenue generated by each customer.
-- 2) Return only customers whose total Revenue is greater than 2000.

with customer_revenue as (
select o.customer_id 
	, SUM(oi.price * oi.quantity ) as revenue
from  order_items oi 
join orders o on o.order_id = oi.order_id
group by 1

)
SELECT *
FROM customer_revenue
where revenue > 2000
;
-- TASK 04

-- Find customers who spent more than the average customer revenue.
-- Use a subquery.
select o.customer_id 
	, SUM(oi.price * oi.quantity ) as revenue
from  order_items oi 
join orders o on o.order_id = oi.order_id
group by 1
HAVING SUM(oi.price * oi.quantity) > (
    SELECT AVG(customer_revenue)
    FROM (
        SELECT o2.customer_id,
               SUM(oi2.price * oi2.quantity) AS customer_revenue
        FROM orders o2
        JOIN order_items oi2
            ON o2.order_id = oi2.order_id
        group by 1
        )AS revenue_by_customer);


-- TASK 05

-- Use ROW_NUMBER() to number each customer's purchases
-- in chronological order.
SELECT o.customer_id
	,o.order_id
    , o.order_date
    , ROW_NUMBER() OVER (
        PARTITION BY o.customer_id
        ORDER BY o.order_date
    ) AS purchase_number
FROM orders o;

