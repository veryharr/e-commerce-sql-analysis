-- TASK 01
-- Calculate the total number of orders.


select count( o.order_id ) as Total_orders
from orders o ;

-- TASK 02
-- Calculate the total number of unique customers.

select count( Distinct(o.customer_id ) ) as Unique_custumers
from orders o ;

-- TASK 03
-- Calculate the total number of unique products.

select count( Distinct(oi.product_id ) ) as unique_products
from order_items oi  ;


-- TASK 04
-- Calculate the total number of units sold.

select SUM(oi.quantity) as total_units_sold
from order_items oi  ;

-- TASK 05
-- Calculate the total revenue generated by the store.

select SUM(oi.price*oi.quantity) as revenue
from order_items oi  ;

-- TASK 06
-- Calculate the average order value (AOV).


select SUM(oi.price*oi.quantity) / COUNT(DISTINCT oi.order_id) as aov
from order_items oi  ;

-- TASK 07
-- Calculate the number of orders for each order status.
-- Show the status and the number of orders.

select o.status,
	count(o.status) as nmbr_status
	from orders o 
	group by o.status 
	;

-- TASK 08
-- Calculate the number of customers from each country.
-- Show the country and the number of unique customers.


select c.country,
	COUNT(DISTINCT customer_id) as amnt_each_cntr
	from customers c 
	group by c.country
	;

-- TASK 09
-- Calculate the number of orders for each month.
-- Show the month and the number of orders.


select
	DATE_TRUNC( 'month', o.order_date::DATE),
	count(o.order_id )
	from orders o 
	group by 1
	;

-- TASK 10
-- Calculate the total revenue for each month.
-- Show the month and the revenue.

select SUM(oi.price  * oi.quantity ),
	DATE_TRUNC( 'month', o.order_date::DATE) as monthes
	from orders o 
	join order_items oi on o.order_id = oi.order_id 
	group by 2
	;