-- Business Questions: Customer Analysis
-- This section analyzes customer behavior and value,
-- including customer distribution, order frequency, revenue contribution, and high-value customers.
-- ==========================================

-- TASK 01

-- Find the total number of customers.

select COUNT(distinct c.customer_id ) as TNC
	from customers c 
	;

-- TASK 02

-- Find the number of customers in each country.


select c.country 
	, COUNT(distinct c.customer_id ) as TNC
	from customers c 
	group by 1
	order by 2 desc
	;

-- TASK 03

-- Find the top 10 countries by number of customers.


select c.country 
	, COUNT(distinct c.customer_id ) as TNC
	from customers c 
	group by 1
	order by 2 desc
	limit 10 
	;



-- TASK 04

-- Find the average number of orders per customer.

WITH count_of_orders_by_customers AS (
select Count(o.order_id/c.customer_id ) as cnt
	, c.customer_id
	from customers c 
	join orders o on c.customer_id =o.customer_id 
	group by 2
)
select ROUND(AVG(cnt), 2) as avg_sorted_count_of_orders
from count_of_orders_by_customers ;

-- TASK 05

-- Find the top 10 customers by total Revenue.

select SUM(oi.quantity * oi.price)
	, o.customer_id as top_10_id_customers_by_revenue
	from order_items oi 
	join orders o on o.order_id = oi.order_id 
	group by 2 
	order by 1 desc
	limit 10
	;
-- TASK 06

-- Find the top 10 customers by number of orders.


select count(o.order_id )
	, o.customer_id 
	from orders o  
	group by 2 
	order by 1 desc
	limit 10
	;

-- TASK 07

-- Find customers who have never placed an order.


select *
	from customers c
left join orders o
    ON c.customer_id = o.customer_id
    where o.customer_id is NULL
	;


-- TASK 08

-- Calculate the average Revenue per customer for each country.

select country
	, SUM(oi.price * oi.quantity) / COUNT(DISTINCT c.customer_id) as avg_per_customers
	from customers c 
	join orders o on c.customer_id = o.customer_id
	join order_items oi on o.order_id = oi.order_id 
	group by 1
	;


-- TASK 09

-- Find the percentage of total Revenue generated by each country.


with rvn as (
select country
, SUM(oi.quantity * oi.price) as k1
from customers c 
	join orders o on c.customer_id = o.customer_id
	join order_items oi on o.order_id = oi.order_id 
	group by 1
),
     rvn1 AS (select SUM(oi.quantity * oi.price) AS total_revenue from order_items oi )
	
	select country
	, (k1*100/rvn1.total_revenue) AS revenue_percentage
	from rvn
	cross join rvn1;
	
	;


-- TASK 10

-- Find the customers who generated more Revenue than the average customer.
	
	
with rvn as (
select o.customer_id 
	, SUM(oi.quantity * oi.price) as k1
from order_items oi 
	join orders o on oi.order_id =o.order_id 
	group by 1
	order by 1 asc
)
select *
from rvn 
where k1>(select avg(k1) from rvn)
	;