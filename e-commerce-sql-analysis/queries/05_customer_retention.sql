-- Business Questions: Customer Retention Analysis
-- This section analyzes customer retention and purchasing behavior,
-- including repeat customers, purchase frequency, and customer retention patterns.
-- ==========================================


-- TASK 01
-- Find customers who placed their first order.

select o.customer_id
	, Min(o.order_date) as first_order
from orders o 
group by 1
order by 1 
;
-- TASK 02
-- Determine the date of the first order for each customer.


select o.customer_id
	, Min(o.order_date) as first_order
from orders o 
group by 1
order by 1 
;
-- TASK 03
-- Determine the date of the last order for each customer.


select o.customer_id
	, Max(o.order_date) as last_order
from orders o 
group by 1
order by 1 
;

-- TASK 04
-- Calculate the number of days between the first and last order for each customer.



select o.customer_id
	, Min(o.order_date) as first_order
	, Max(o.order_date) as last_order
	, MAX(o.order_date)::date - MIN(o.order_date)::date as anount
from orders o 
group by 1
order by 1 
;

-- TASK 05
-- Find customers who made a repeat purchase.


select o.customer_id
	, count(o.order_id) as amount
from orders o 
group by 1
having count(o.order_id)>1 
order by 1 
;


-- TASK 06
-- Calculate the number of new customers acquired each month.


WITH first_orders AS (
		select o.customer_id
			, Min(o.order_date::date) as first_order
		from orders o 
		group by 1
		order by 1 
)

select DATE_TRUNC('month', first_order)
	, count(first_orders.customer_id)
from first_orders
group by 1 
order by 1;


-- TASK 07
-- Determine how many customers returned after their first order.


WITH first_orders AS (
		select o.customer_id
			, Count(o.order_id) as amount
			, Min(o.order_date) as first_order
			, Max(o.order_date) as last_order
		from orders o 
		group by 1
		order by 1 
)

select *
from first_orders
WHERE first_orders.amount > 1
;


-- TASK 08
-- Find customers who have not placed an order for a long time(90 days).

WITH customer_last_orders AS (
    SELECT
        o.customer_id,
        COUNT(DISTINCT o.order_id) AS total_orders,
        MAX(o.order_date::date) AS last_order
    FROM orders o
    GROUP BY o.customer_id
),
dataset_reference AS (
    SELECT MAX(order_date::date) AS reference_date
    FROM orders
)
SELECT
    c.customer_id,
    c.total_orders,
    c.last_order,
    d.reference_date,
    d.reference_date - c.last_order AS days_since_last_order
FROM customer_last_orders c
CROSS JOIN dataset_reference d
WHERE c.last_order <= d.reference_date - 90
ORDER BY days_since_last_order DESC;

-- TASK 09
-- Calculate the Revenue generated by repeat customers.

WITH first_orders AS (
    SELECT o.customer_id,
           COUNT(DISTINCT o.order_id) AS amount,
           SUM(oi.price * oi.quantity) AS revenue
    FROM orders o 
    JOIN order_items oi ON o.order_id = oi.order_id 
    GROUP BY 1
    HAVING COUNT(DISTINCT o.order_id) > 1
    ORDER BY 1 
)
SELECT SUM(first_orders.revenue) AS total_revenue
FROM first_orders;

-- TASK 10
-- Compare Revenue generated by new customers
-- versus Revenue generated by returning customers.



WITH first_orders AS (
    SELECT o.customer_id
           , COUNT(distinct o.order_id) AS amount
           , SUM(oi.price * oi.quantity ) as revenue
    FROM orders o 
    join order_items oi on o.order_id =oi.order_id 
    GROUP BY 1
    having COUNT(distinct o.order_id)>1
    ORDER BY 1 
),

second_orders AS (
    SELECT o.customer_id
           , COUNT(distinct o.order_id) AS amount
           , SUM(oi.price * oi.quantity ) as revenue
    FROM orders o 
    join order_items oi on o.order_id =oi.order_id 
    GROUP BY 1
    having COUNT(distinct o.order_id)=1
    ORDER BY 1 
)
SELECT 'Returning customers' AS customer_type
	, SUM(first_orders.revenue) as revenue
FROM first_orders

UNION ALL

SELECT 'New customers' AS customer_type
	, SUM(second_orders.revenue) as revenue
FROM second_orders
;
